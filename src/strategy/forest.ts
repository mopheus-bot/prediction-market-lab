/**
 * prediction-market-lab — pure-TS RandomForest inference.
 *
 * Reads the JSON format emitted by
 * `scripts/convert-models-to-json.py` and produces
 * `predict_proba`-style class probabilities.
 *
 * **No external deps.** This is a hand-rolled inference
 * engine because Cloudflare Workers + onnxruntime-web is
 * a 5MB+ WASM blob that doesn't fit comfortably in a DO
 * cold-start. The RandomForest structure is simple enough
 * that a hand-rolled walker is faster than JITted WASM for
 * these small models anyway (200 trees * ~50 nodes each).
 *
 * **The model format:** each tree is a flat node-table
 * (sklearn's native storage). Nodes are referenced by
 * index. `feature[i] === -2` means leaf i; `left[i] === -1`
 * means leaf i (both checks for safety — sklearn uses both
 * conventions across versions). `value[i] = [n_class_0,
 * n_class_1,...]` is the per-class sample count at node i;
 * for leaves this is the raw class counts in the training
 * samples that landed at this node, and `predict_proba` is
 * the average across all trees normalized to a unit sum.
 *
 * **Parity:** the `model-parity-*.json` fixtures in
 * `test/fixtures/` were generated by running the same
 * feature vectors through the original.joblib model.
 * `test/forest.test.ts` asserts the TS output matches
 * the Python output to 1e-9.
 *
 * **Thread safety:** immutable after construction. The DO
 * constructs one `RandomForestModel` per vertical at /start
 * time and reuses it across every signal call.
 */

import type { Vertical } from "../lib/types.js";

// ─── JSON shape ────────────────────────────────────────────────────────

export interface RandomForestJSON {
	version: 1;
	format: "sklearn-randomforest-v1";
	n_features: number;
	n_classes: number;
	classes: number[];
	n_estimators: number;
	max_depth: number;
	feature_importances: number[];
	trees: Array<{
		n_nodes: number;
		/** feature index for the split, or -2 for a leaf. */
		feature: number[];
		/** Split threshold (float). */
		threshold: number[];
		/** Child node index (left of split), or -1 for a leaf. */
		left: number[];
		/** Child node index (right of split), or -1 for a leaf. */
		right: number[];
		/** Per-class sample count at this node. (n_nodes, n_classes) */
		value: number[][];
	}>;
}

// ─── Loader + inference ────────────────────────────────────────────────

/** An immutable, parsed RandomForest model. */
export class RandomForestModel {
	readonly n_features: number;
	readonly n_classes: number;
	readonly classes: number[];
	readonly n_estimators: number;
	readonly max_depth: number;
	readonly feature_importances: ReadonlyArray<number>;
	private readonly trees: ReadonlyArray<ParsedTree>;

	constructor(json: RandomForestJSON) {
		if (json.format !== "sklearn-randomforest-v1") {
			throw new Error(
				`unsupported model format: ${json.format}; ` +
					`expected "sklearn-randomforest-v1"`,
			);
		}
		if (json.version !== 1) {
			throw new Error(`unsupported model version: ${json.version}`);
		}
		this.n_features = json.n_features;
		this.n_classes = json.n_classes;
		this.classes = [...json.classes];
		this.n_estimators = json.n_estimators;
		this.max_depth = json.max_depth;
		this.feature_importances = Object.freeze([...json.feature_importances]);
		this.trees = json.trees.map(parseTree);
	}

	/**
	 * Predict class probabilities for one feature vector.
	 * Returns a length-`n_classes` array summing to ~1.0.
	 * The array is in the same order as `this.classes`.
	 */
	predictProbaOne(features: ReadonlyArray<number>): number[] {
		if (features.length !== this.n_features) {
			throw new Error(
				`features has ${features.length} dims, model expects ${this.n_features}`,
			);
		}
		const accum = new Array<number>(this.n_classes).fill(0);
		for (const tree of this.trees) {
			const leafValue = walkTree(tree, features);
			for (let c = 0; c < this.n_classes; c++) {
				accum[c] += leafValue[c];
			}
		}
		const total = accum.reduce((a, b) => a + b, 0);
		if (total <= 0) {
			// Pathological case: all leaves have value 0. Return
			// uniform 1/n_classes to avoid NaN. Should not happen
			// with a trained model.
			return accum.map(() => 1 / this.n_classes);
		}
		return accum.map((v) => v / total);
	}

	/**
	 * Predict class probabilities for a 2-D batch (n_samples, n_features).
	 * Returns a 2-D array (n_samples, n_classes).
	 */
	predictProba(features2d: ReadonlyArray<ReadonlyArray<number>>): number[][] {
		return features2d.map((row) => this.predictProbaOne(row));
	}
}

// ─── Tree-walking internals ────────────────────────────────────────────

interface ParsedTree {
	feature: Int32Array;
	threshold: Float64Array;
	left: Int32Array;
	right: Int32Array;
	value: Float64Array[]; // length n_nodes, each a Float64Array of length n_classes
}

/**
 * Walk a single tree to a leaf and return the per-class sample
 * count at that leaf. Pure function (no allocations in the hot
 * path) — the inner loop reads from typed arrays.
 */
function walkTree(tree: ParsedTree, features: ReadonlyArray<number>): Float64Array {
	let node = 0;
	// Tight inner loop. sklearn's tree structure guarantees
	// termination (every step goes strictly deeper, and max_depth
	// caps the depth).
	// eslint-disable-next-line no-constant-condition
	while (true) {
		const f = tree.feature[node];
		if (f < 0) {
			// Leaf node. -2 per our export format, but we also
			// check `left` defensively.
			return tree.value[node];
		}
		const t = tree.threshold[node];
		// `features[f] <= t` matches sklearn's `<=` convention.
		node = features[f] <= t ? tree.left[node]: tree.right[node];
		if (node < 0) {
			// Defensive: should match the f < 0 case above.
			return tree.value[-node - 1];
		}
	}
}

function parseTree(raw: RandomForestJSON["trees"][number]): ParsedTree {
	if (raw.n_nodes <= 0) {
		throw new Error(`tree has n_nodes=${raw.n_nodes}; expected > 0`);
	}
	if (
		raw.feature.length !== raw.n_nodes ||
		raw.threshold.length !== raw.n_nodes ||
		raw.left.length !== raw.n_nodes ||
		raw.right.length !== raw.n_nodes ||
		raw.value.length !== raw.n_nodes
	) {
		throw new Error(
			`tree arrays length mismatch: feature=${raw.feature.length} ` +
				`threshold=${raw.threshold.length} left=${raw.left.length} ` +
				`right=${raw.right.length} value=${raw.value.length} n_nodes=${raw.n_nodes}`,
		);
	}
	return {
		feature: Int32Array.from(raw.feature),
		threshold: Float64Array.from(raw.threshold),
		left: Int32Array.from(raw.left),
		right: Int32Array.from(raw.right),
		value: raw.value.map((row) => Float64Array.from(row)),
	};
}

// ─── Helpers ──────────────────────────────────────────────────────────

/**
 * Load a model from a JSON string (e.g. an R2 fetch result).
 */
export function loadForestFromJSON(jsonString: string): RandomForestModel {
	const parsed = JSON.parse(jsonString) as RandomForestJSON;
	return new RandomForestModel(parsed);
}

/** A vertical-keyed model bundle. */
export type ModelBundle = Partial<Record<Vertical, RandomForestModel>>;
